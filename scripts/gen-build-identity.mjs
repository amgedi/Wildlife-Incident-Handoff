/** Generates src/build-identity.ts with the current commit, build time and a
 *  frontend build id (hash of dist assets when present, else of source).
 *  Run automatically before every `npm run build` (see package.json prebuild). */
import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();

function gitCommit() {
  try {
    return execSync("git rev-parse --short=7 HEAD", { cwd: root, encoding: "utf-8" }).trim();
  } catch {
    return "unknown";
  }
}

function hashDir(dir) {
  const h = createHash("sha256");
  const walk = (d) => {
    for (const entry of readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const p = join(d, entry.name);
      if (entry.isDirectory()) walk(p);
      else h.update(readFileSync(p));
    }
  };
  walk(dir);
  return h.digest("hex").slice(0, 12);
}

let bundleId = "dev";
const dist = join(root, "dist");
if (existsSync(dist)) {
  bundleId = hashDir(dist);
} else {
  // pre-build: hash the source tree (stable enough to identify the input)
  const src = join(root, "src");
  bundleId = hashDir(src);
}

const time = new Date().toISOString().replace("T", " ").slice(0, 16);
const template = `/** Build identity \u2014 generated by scripts/gen-build-identity.mjs at build time.
 *  DO NOT EDIT BY HAND. Surfaces in Settings \u2192 About so a stale/crossed build
 *  is immediately diagnosable (0.3.0-dev.4 spec 1, 48). */
export const BUILD_COMMIT = ${JSON.stringify(gitCommit())};
export const BUILD_TIME = ${JSON.stringify(time)};
export const FRONTEND_BUILD_ID = ${JSON.stringify(bundleId)};
`;
writeFileSync(join(root, "src", "build-identity.ts"), template, "utf-8");
console.log(`build identity: commit ${gitCommit()} time ${time} id ${bundleId}`);
